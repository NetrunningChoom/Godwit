//! Steam voice chat (1:1 calls and group voice channels), in progress.
//!
//! Steam's client voice is WebRTC: signaling goes over the client connection
//! ([`signaling`]), media directly to Steam's voice servers. Steam publishes no
//! spec; the messages are from Steam's own protobufs (`proto/voice.proto`) and
//! the call order follows vaporchat (https://github.com/vaporlens/vaporchat,
//! MIT), an unofficial client that has this working.
//!
//! Not wired into the app yet: the peer connection (libwebrtc through
//! livekit, microphone and playback from godwit-voice) and the session state
//! machine come next.

// Generated by rust-protobuf (see proto/voice.proto); its accessors unwrap.
#[allow(clippy::unwrap_used, clippy::expect_used)]
pub mod proto;
mod rpc;
pub mod sdp;
pub mod session;
pub mod signaling;
